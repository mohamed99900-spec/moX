NAME_RE = re.compile(r"(?:^|\s)(?:يا\s+)?(?:مو|موكس|mox|بوت)(?=$|[\s!?؟.,،~]+)", re.I)


def extract_call(text: str):
    """يرجع (نودي على البوت؟, باقي الكلام بعد حذف الاسم)."""
    m = NAME_RE.search(text)
    if not m:
        return False, text
    rest = (text[:m.start()] + " " + text[m.end():]).strip()
    return True, rest


