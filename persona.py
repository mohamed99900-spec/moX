def honorific(user: types.User) -> str:
    u = peek_user(user.id)
    lvl = level_of(u["score"])[0][1] if u else "مبتدئ"
    return random.choice(HONORIFICS[lvl])


def call(user: types.User) -> str:
    """الاسم + اللقب، جاهز للاستخدام داخل HTML."""
    return f"{honorific(user)} <b>{esc(user.first_name)}</b>"


