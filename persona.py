LAST_REPLY: dict = {}


def fun_filter(message: types.Message):
    t = (message.text or "").strip()
    if not t or t.startswith("/") or len(t) > 60:
        return False
    if message.from_user is None or message.from_user.is_bot:
        return False
    called, rest = extract_call(t)
    if called:
        if len(rest) >= 12:       # سؤال حقيقي -> يروح للذكاء الاصطناعي
            return False
        return {"replies": CALL_REPLIES, "always": True}
    for rx, replies in RULES:
        if rx.search(t):
            return {"replies": replies, "always": False}
    return False


@fun_router.message(fun_filter)
async def fun_reply(message: types.Message, replies: list, always: bool):
    private = message.chat.type == "private"
    if not private:
        now = time.time()
        last = LAST_REPLY.get(message.chat.id, 0)
        if always:
            if now - last < 3:
                return
        else:
            if now - last < 15 or random.random() > 0.65:
                return
        LAST_REPLY[message.chat.id] = now
    text = random.choice(replies).format(n=call(message.from_user))
    await message.reply(text, parse_mode="HTML")


