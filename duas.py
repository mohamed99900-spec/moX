ALL = [(c, t, s) for c, items in CATS for t, s in items if s]

MENU_TEXT = ("🤲 <b>أذكار وأدعية</b>\n\n"
             "اختار القسم، أو دوس <b>ذكر عشوائي</b> 🎲\n"
             "<i>مأخوذة من القرآن والسنة الصحيحة (حصن المسلم)</i>")


def menu_kb():
    rows, row = [], []
    for i, (name, _) in enumerate(CATS):
        row.append(Btn(text=name, callback_data=f"du:{i}"))
        if len(row) == 2:
            rows.append(row)
            row = []
    if row:
        rows.append(row)
    rows.append([Btn(text="🎲 ذكر عشوائي", callback_data="du:r")])
    rows.append([Btn(text="🏠 القائمة الرئيسية", callback_data="main_menu")])
    return InlineKeyboardMarkup(inline_keyboard=rows)


def cat_text(i: int) -> str:
    name, items = CATS[i]
    out = [f"<b>{name}</b>\n"]
    for t, s in items:
        out.append(f"• {esc(t)}" + (f"\n   <i>({esc(s)})</i>" if s else ""))
    return "\n\n".join(out)


@duas_router.callback_query(F.data == "duas_menu")
async def menu_cb(callback: types.CallbackQuery):
    await callback.answer()
    await show(callback, MENU_TEXT, menu_kb())


@duas_router.message(or_f(Command("duas"), F.text.in_(["ادعية", "أدعية", "اذكار", "أذكار", "دعاء", "ادعيه", "اذكار وادعية"])))
async def menu_msg(message: types.Message):
    await safe_answer(message, MENU_TEXT, menu_kb())


def back_kb(extra=None):
    rows = []
    if extra:
        rows.append(extra)
    rows.append([Btn(text="🤲 الأقسام", callback_data="duas_menu"), Btn(text="🏠 الرئيسية", callback_data="main_menu")])
    return InlineKeyboardMarkup(inline_keyboard=rows)


@duas_router.callback_query(F.data.startswith("du:"))
async def cat_cb(callback: types.CallbackQuery):
    await callback.answer()
    key = callback.data.split(":")[1]
    if key == "r":
        c, t, s = random.choice(ALL)
        text = f"🎲 <b>ذكر عشوائي</b> — {c}\n\n{esc(t)}" + (f"\n\n<i>({esc(s)})</i>" if s else "")
        await show(callback, text, back_kb([Btn(text="🎲 ذكر تاني", callback_data="du:r")]))
        return
    await show(callback, cat_text(int(key)), back_kb())


@duas_router.message(F.text.in_(["اذكار الصباح", "أذكار الصباح"]))
async def morning(message: types.Message):
    await safe_answer(message, cat_text(0), back_kb())


@duas_router.message(F.text.in_(["اذكار المساء", "أذكار المساء"]))
async def evening(message: types.Message):
    await safe_answer(message, cat_text(1), back_kb())


